"""BUILD-RECORD.md and EDIT-TEST-RECORD.md for the WALL designs, from the post-run outputs.

    python3 v2/01-CAD-Native/wall/make_records.py

Reads v2/03-Manufacturing/wall/out/<pn>.json (CAD reports) and v2/01-CAD-Native/wall/out/edit-<pn>.md
(edit test records), both written in Fusion by post_wall_doc.py, and writes the two records here.
"""

import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPORTS = os.path.join(HERE, "..", "..", "03-Manufacturing", "wall", "out")


def main():
    reps = []
    for path in sorted(glob.glob(os.path.join(REPORTS, "*.json"))):
        with open(path, encoding="utf-8") as fh:
            reps.append(json.load(fh))
    lines = ["# Build record: WALL designs", "",
             "Generated by `make_records.py` from the CAD reports that `post_wall_doc.py` writes in Fusion (2706.1, "
             "Mac 1) after each build. Every design derives skeleton P04 (`100000_P04_POD-SKELETON_CAD`); its "
             "exported .f3d carries the skeleton's values with the derive link broken for the export only, so it "
             "opens on its own (README, Fusion traps). STEP length unit: cm, declared in the file (D-13).", "",
             "| Design | Cloud version | Components | Bodies | Holes | Mass of made parts (kg) | Files |",
             "|---|---|---|---|---|---|---|"]
    for r in reps:
        comps = [c for c in r["components"] if not c["is_root"]]
        bodies = sum(len(c["bodies"]) for c in comps)
        holes = sum(len(b["holes"]) for c in comps for b in c["bodies"])
        mass = sum(b["mass_kg"] for c in comps if not c["part_number"].startswith("NO-PN") for b in c["bodies"])
        name = r["document"]
        files = "`%s.f3d`, `%s_STEP.step`" % (name, name[:-4])
        lines.append("| %s | v%s | %s | %d | %d | %.3f | %s |" % (
            name, r["version"], ", ".join(sorted(c["part_number"] for c in comps)), bodies, holes, mass, files))
    lines += ["", "Masses per component (kg, CAD, at the densities in each design's material names):", ""]
    for r in reps:
        for c in r["components"]:
            if c["bodies"] and not c["is_root"]:
                lines.append("- %s %s: %.3f (%d bodies)" % (c["part_number"], c["name"].split(" ", 1)[-1],
                                                          sum(b["mass_kg"] for b in c["bodies"]), len(c["bodies"])))
    with open(os.path.join(HERE, "BUILD-RECORD.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    edits = sorted(glob.glob(os.path.join(HERE, "out", "edit-*.md")))
    out = ["# Edit test record: WALL designs", "",
           "Guideline section 4.4. `edit_test_wall.py` (run by `post_wall_doc.py`) opens each exported .f3d as a "
           "new, unsaved copy, changes two skeleton values and one wall rule (wall_depth 1495 -> 1300, side_h -> "
           "1000, stile_pitch_max 400 -> 300), checks that every part follows and every feature stays healthy, then "
           "reverts and checks that every body is back to its exact box. The copy is closed without saving.", ""]
    for p in edits:
        with open(p, encoding="utf-8") as fh:
            out.append(fh.read().strip())
            out.append("")
    with open(os.path.join(HERE, "EDIT-TEST-RECORD.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("BUILD-RECORD.md: %d designs; EDIT-TEST-RECORD.md: %d records" % (len(reps), len(edits)))


if __name__ == "__main__":
    main()
